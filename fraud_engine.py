"""Shared preprocessing and alert policy for the Arch Store offline SOC lab."""

from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path
import argparse
import json

import joblib
import numpy as np
import pandas as pd

FEATURE_COLUMNS = ["Time", *[f"V{i}" for i in range(1, 29)], "Amount"]
SCALED_COLUMNS = [*[f"V{i}" for i in range(1, 29)], "scaled_amount", "scaled_time"]
THRESHOLD = 0.50  # Fixed before the holdout evaluation; not tuned on test labels.
MODEL_VERSION = "arch-rf-smote-v1"


def validate_features(frame: pd.DataFrame) -> pd.DataFrame:
    """Require the 30 numeric benchmark fields, with no label or extra columns."""
    missing = sorted(set(FEATURE_COLUMNS) - set(frame.columns))
    extra = sorted(set(frame.columns) - set(FEATURE_COLUMNS))
    if missing or extra or frame.columns.duplicated().any():
        raise ValueError(f"Feature schema mismatch. Missing={missing}; extra={extra}")
    selected = frame.loc[:, FEATURE_COLUMNS]
    if not all(pd.api.types.is_numeric_dtype(dtype) for dtype in selected.dtypes):
        raise ValueError("All transaction features must be numeric.")
    if not np.isfinite(selected.to_numpy(dtype=float)).all():
        raise ValueError("Features must be finite; missing values are not accepted.")
    return selected


def transform_transactions(frame: pd.DataFrame, scaler) -> pd.DataFrame:
    """Reuse the training-only scaler at evaluation and inference time."""
    frame = validate_features(frame)
    values = scaler.transform(frame.loc[:, ["Amount", "Time"]])
    transformed = frame.loc[:, [f"V{i}" for i in range(1, 29)]].copy()
    transformed["scaled_amount"] = values[:, 0]
    transformed["scaled_time"] = values[:, 1]
    return transformed.loc[:, SCALED_COLUMNS]


def score_transactions(frame: pd.DataFrame, bundle: dict, transaction_ids=None) -> list[dict]:
    """Emit HIGH review alerts only. No payment blocking or external transmission."""
    features = validate_features(frame)
    if transaction_ids is None:
        transaction_ids = [f"transaction-{i}" for i in range(len(features))]
    transaction_ids = list(transaction_ids)
    if len(transaction_ids) != len(features):
        raise ValueError("Provide exactly one transaction ID per row.")
    if len(set(map(str, transaction_ids))) != len(transaction_ids):
        raise ValueError("Transaction IDs must be unique within a batch.")
    if not len(features):
        return []
    scores = bundle["model"].predict_proba(
        transform_transactions(features, bundle["scaler"])
    )[:, 1]
    threshold = float(bundle["threshold"])
    if not 0 < threshold <= 1:
        raise ValueError("Alert threshold must be in (0, 1].")
    now = datetime.now(timezone.utc).isoformat()
    return [
        {
            "event_type": "transaction_fraud_suspected",
            "detection_id": "ARCH-ML-001",
            "model_version": bundle["model_version"],
            "transaction_id": str(transaction_ids[i]),
            "severity": "HIGH",
            "score": round(float(score), 8),
            "threshold": threshold,
            "action": "analyst_review",
            "generated_at_utc": now,
            "reason": "Random Forest fraud score meets the fixed alert threshold",
        }
        for i, score in enumerate(scores)
        if score >= threshold
    ]


def main() -> None:
    parser = argparse.ArgumentParser(description="Score anonymized benchmark transactions.")
    parser.add_argument("--input", type=Path, required=True, help="CSV containing exactly 30 features")
    parser.add_argument("--model", type=Path, default=Path("models/fraud_engine.joblib"))
    parser.add_argument("--output", type=Path, required=True, help="HIGH alerts as JSONL")
    args = parser.parse_args()
    # Load only the trusted model generated by this project's notebook.
    bundle = joblib.load(args.model)
    frame = pd.read_csv(args.input)
    alerts = score_transactions(frame, bundle)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("".join(json.dumps(item) + "\n" for item in alerts), encoding="utf-8")
    print(json.dumps({"transactions": len(frame), "high_severity_alerts": len(alerts),
                      "suppressed": len(frame) - len(alerts), "threshold": bundle["threshold"]}))


if __name__ == "__main__":
    main()
